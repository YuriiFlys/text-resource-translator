INSERT INTO i18n_translation (text_id, locale_code, translated_text)
SELECT t.text_id, 'en', seed.source_text
FROM seed JOIN i18n_text t USING (text_code)
ON CONFLICT (text_id, locale_code) DO UPDATE
SET translated_text = EXCLUDED.translated_text, date_updated = now()
WHERE i18n_translation.translated_text IS DISTINCT FROM EXCLUDED.translated_text;
